func builtInTitleI18n(title string) map[string]string {
	return builtInLocalizedText(title, builtInAPIEnglishTitles)
}

func builtInDescriptionI18n(description string) map[string]string {
	return builtInLocalizedText(description, builtInAPIEnglishDescriptions)
}

func builtInLocalizedText(zhText string, english map[string]string) map[string]string {
	localized := map[string]string{i18n.LocaleZhCN: zhText}
	if enText := english[zhText]; enText != "" {
		localized[i18n.LocaleEnUS] = enText
	}
	return localized
}

func cloneLocalizedText(source map[string]string) map[string]string {
	if len(source) == 0 {
		return nil
	}
	cloned := make(map[string]string, len(source))
	for locale, text := range source {
		cloned[locale] = text
	}
	return cloned
}
